#!/bin/bash
echo "=============================================="
echo "    Импорт прошлых трансляций (VK + YouTube)  "
echo "=============================================="

# Переходим в папку бекенда
cd telegram_hls_backend || exit

# Проверка наличия файла vk_links.txt
if [ ! -f "../vk_links.txt" ]; then
    echo "ВНИМАНИЕ: Файл vk_links.txt не найден в корневой папке."
    echo "Скрипт загрузит только видео с YouTube."
else
    echo "Файл vk_links.txt найден. Будут обработаны видео из VK и YouTube."
fi
echo "=============================================="

# Устанавливаем зависимости на всякий случай
npm install > /dev/null 2>&1

# Запускаем скрипт
node import_legacy.js

echo "=============================================="
echo "Импорт завершен! Нажмите любую клавишу для выхода..."
read -n 1 -s
